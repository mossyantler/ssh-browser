import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const require = createRequire(join(root, 'package.json'));
const destination = join(root, 'extension/vendor/primer');
const expectedVersion = '22.3.2';
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
  throw new Error('Usage: node scripts/vendor-primer.mjs [--check]');
}
const check = args[0] === '--check';
const project = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'));
const lock = JSON.parse(await readFile(join(root, 'package-lock.json'), 'utf8'));
if (project.devDependencies?.['@primer/css'] !== expectedVersion ||
    lock.packages?.['']?.devDependencies?.['@primer/css'] !== expectedVersion) {
  throw new Error(`@primer/css must be pinned to exactly ${expectedVersion} in package.json and package-lock.json.`);
}

async function packageSource(name, version) {
  const packagePath = require.resolve(`${name}/package.json`);
  const metadata = JSON.parse(await readFile(packagePath, 'utf8'));
  const locked = lock.packages?.[`node_modules/${name}`];
  if (!locked || metadata.name !== name || metadata.version !== locked.version ||
      (version && metadata.version !== version)) {
    throw new Error(`${name} installation does not match the pinned lockfile. Run npm ci.`);
  }
  if (metadata.license !== 'MIT' || !locked.resolved || !locked.integrity) {
    throw new Error(`${name} must have an MIT license and lockfile provenance.`);
  }
  return {
    directory: dirname(packagePath),
    provenance: {
      name,
      version: metadata.version,
      license: metadata.license,
      resolved: locked.resolved,
      integrity: locked.integrity,
    },
  };
}

const primer = await packageSource('@primer/css', expectedVersion);
// npm installs this peer automatically; its notice also covers the bundled tokens.
// Its installed version is recorded, not claimed as the original CSS build input.
const primitives = await packageSource('@primer/primitives');
const inputs = [
  [primer, 'dist/primer.css', 'primer.css'],
  [primer, 'dist/primer.css.map', 'primer.css.map'],
  [primer, 'LICENSE', 'LICENSE'],
  [primitives, 'LICENSE', 'PRIMITIVES_LICENSE'],
];
const output = new Map();
const files = [];
for (const [source, sourcePath, destinationPath] of inputs) {
  const bytes = await readFile(join(source.directory, sourcePath));
  output.set(destinationPath, bytes);
  files.push({
    path: destinationPath,
    sourcePackage: source.provenance.name,
    sourcePath,
    bytes: bytes.length,
    sha256: createHash('sha256').update(bytes).digest('hex'),
  });
}

const css = output.get('primer.css').toString('utf8');
if (/@import\b/.test(css) || [...css.matchAll(/url\(\s*["']?([^\s)"']+)/g)].some((match) => !match[1].startsWith('data:'))) {
  throw new Error('Expected self-contained Primer CSS with embedded assets only.');
}
const themes = [...new Set([...css.matchAll(/\[data-(?:light|dark)-theme=([^\]]+)\]/g)].map((match) => match[1]))];
const manifest = {
  schemaVersion: 1,
  generatedBy: 'npm run vendor:primer',
  packages: [primer.provenance, primitives.provenance],
  themeAttributes: {
    mode: 'data-color-mode',
    modes: ['light', 'dark', 'auto'],
    lightTheme: 'data-light-theme',
    darkTheme: 'data-dark-theme',
    themes,
  },
  files,
};
output.set('manifest.json', Buffer.from(`${JSON.stringify(manifest, null, 2)}\n`));
output.set('README.md', Buffer.from(`# Primer CSS vendor assets

This directory is generated by \`npm run vendor:primer\` from the official npm
package \`@primer/css@${expectedVersion}\`. Run \`npm ci\` first. Verify committed
assets without writing files with \`npm run vendor:primer:check\` (or
\`npm run vendor:primer -- --check\`). The script works independently of the
current working directory and copies package files byte for byte.

Load \`vendor/primer/primer.css\` from extension HTML before application styles.
The compiled stylesheet already includes design tokens, primitives and themes;
it needs no additional runtime stylesheet, JavaScript, CDN or network assets.
The original source map is included for the stylesheet's sourceMappingURL.
It is preserved verbatim: the upstream map references a CI file path and has
no embedded sourcesContent, so local Sass source debugging is unavailable.

Set theme attributes on the document's root element:

\`\`\`html
<html data-color-mode="light" data-light-theme="light" data-dark-theme="dark">
\`\`\`

Use \`data-color-mode="dark"\` for dark mode, or \`data-color-mode="auto"\` to
follow \`prefers-color-scheme\`. Keep both theme attributes set for auto mode.
Available theme values in this exact compiled release are:

${themes.map((theme) => `- \`${theme}\``).join('\n')}

\`manifest.json\` records npm versions, lockfile tarball URLs/integrities, source
paths, byte sizes and SHA256 hashes. It contains no timestamps or machine paths.
\`LICENSE\` preserves the Primer CSS MIT notice (GitHub Inc., 2021).
\`PRIMITIVES_LICENSE\` preserves the installed peer's MIT notice for token
attribution. npm installs \`@primer/primitives\` as a peer dependency; its
recorded version describes the local locked peer, not the version originally
used to build the published Primer CSS package. No direct primitives dependency
or separate primitives stylesheet is needed to consume this compiled CSS.
`));

if (check) {
  const differences = [];
  for (const [name, expected] of output) {
    try {
      const actual = await readFile(join(destination, name));
      if (!actual.equals(expected)) differences.push(`${name}: differs from package/generated content`);
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
      differences.push(`${name}: missing`);
    }
  }
  if (differences.length) {
    throw new Error(`Primer vendor verification failed:\n${differences.join('\n')}\nRun npm run vendor:primer to regenerate.`);
  }
  console.log(`Verified ${output.size} Primer vendor files against @primer/css@${expectedVersion}.`);
} else {
  await mkdir(destination, { recursive: true });
  for (const [name, bytes] of output) await writeFile(join(destination, name), bytes);
  console.log(`Vendored ${output.size} files from @primer/css@${expectedVersion} to extension/vendor/primer.`);
}
